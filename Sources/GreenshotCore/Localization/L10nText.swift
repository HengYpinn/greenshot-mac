import Foundation

/// Texts of the language packs that aren't plain UI literals (upstream `Greenshot.Base/Languages/Texts.cs`,
/// docs/translations.md). The tables are in the app's `<lproj>.lproj/Upstream.strings`; tests, greenshot-cli and the
/// other helpers have none and get the English.
public enum L10nText {
    /// The table of every upstream English text without placeholders and its translation, generated by
    /// scripts/l10n/l10n.py.
    public static let upstreamTable = "Upstream"
    /// The key of the translator credit (upstream `about_translation`) in that table.
    public static let creditKey = "__about_translation__"

    /// An English text that is also data (a built-in recipe's name): its upstream translation from the app's `Upstream`
    /// table, else the text itself (tests, helpers). Only an upstream text exactly as written has one.
    public static func display(_ english: String, bundle: Bundle = .main) -> String {
        guard !english.isEmpty else { return english }
        return bundle.localizedString(forKey: english, value: english, table: upstreamTable)
    }

    /// Upstream `about_translation` of the language in use, nil when there is none.
    public static func translationCredit(bundle: Bundle = .main) -> String? {
        let credit = bundle.localizedString(forKey: creditKey, value: "", table: upstreamTable)
        let trimmed = credit.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty || trimmed == creditKey ? nil : trimmed
    }
}
