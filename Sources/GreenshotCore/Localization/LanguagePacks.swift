import Foundation

/// One of upstream's language packs (`Languages/greenshot.<ietf>.ini`, upstream `LanguageInfo`) and the Apple
/// localization the app ships it as (`Resources/Localizations/<lproj>.lproj`, docs/translations.md).
public struct LanguagePack: Equatable, Hashable, Sendable {
    /// Upstream's code, the value of the `language` setting and of `--language`: "de-DE".
    public let ietf: String
    /// The Apple localization: "de", "zh-Hans", "ca-ES-valencia".
    public let lproj: String
    /// The pack's own name (`Description=` of its ini file), shown in the language lists: "Deutsch".
    public let description: String
    /// Arabic, Persian and Hebrew: the windows are mirrored.
    public let rightToLeft: Bool
    /// The help page of the language in `Resources/Help` (upstream `help-<ietf>.html`), nil when upstream has none.
    public let helpFile: String?

    public init(ietf: String, lproj: String, description: String, rightToLeft: Bool, helpFile: String?) {
        self.ietf = ietf
        self.lproj = lproj
        self.description = description
        self.rightToLeft = rightToLeft
        self.helpFile = helpFile
    }
}

/// The language packs (upstream `LanguageConfig.GetLanguages`); `all` is generated by scripts/l10n/l10n.py.
public enum LanguagePacks {
    /// The base language, every text's key.
    public static var english: LanguagePack {
        all.first { $0.ietf == "en-US" } ?? LanguagePack(ietf: "en-US", lproj: "en", description: "English",
                                                          rightToLeft: false, helpFile: "help-en-US.html")
    }

    /// The word for "as macOS chooses" in `--language` and the `language` setting (stored as "").
    public static let systemCode = "system"

    /// The pack of `code`: upstream's code or the Apple localization, `-` or `_`, any case ("de-DE", "de_de", "de",
    /// "zh-Hans", "va-VA", "ca-ES-valencia"); otherwise the closest by dropping subtags ("de-AT" → de-DE, "zh-Hans-CN"
    /// → zh-CN) and finally by language alone ("pt" → pt-BR, the first of upstream's order). Nil for an unknown
    /// language, "", and "system".
    public static func resolve(_ code: String) -> LanguagePack? {
        let wanted = code.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "_", with: "-")
            .lowercased()
        guard !wanted.isEmpty, wanted != systemCode else { return nil }
        var subtags = wanted.split(separator: "-").map(String.init)
        while !subtags.isEmpty {
            let candidate = subtags.joined(separator: "-")
            if let pack = all.first(where: { $0.ietf.lowercased() == candidate || $0.lproj.lowercased() == candidate }) {
                return pack
            }
            subtags.removeLast()
        }
        let language = String(wanted.split(separator: "-").first ?? "")
        return all.first { $0.lproj.lowercased().split(separator: "-").first.map(String.init) == language }
    }

    /// The language the app's texts are in: the pack of the localization macOS loaded (`preferredLocalizations`),
    /// English when there is none (tests, helpers, a development build without translations).
    public static func inUse(preferredLocalizations: [String] = Bundle.main.preferredLocalizations) -> LanguagePack {
        preferredLocalizations.first.flatMap(pack(lproj:)) ?? english
    }

    /// The pack shipped as `lproj` ("de", "zh-Hans").
    public static func pack(lproj: String) -> LanguagePack? {
        all.first { $0.lproj.caseInsensitiveCompare(lproj) == .orderedSame }
    }

    /// The packs as the language lists show them: by name.
    public static var byName: [LanguagePack] {
        all.sorted { $0.description.localizedStandardCompare($1.description) == .orderedAscending }
    }
}
