import AppKit
import GreenshotCore
import SwiftUI
import UniformTypeIdentifiers

/// Self-Service › Clipboard: the Mac's version of upstream `ClipboardSectionViewModel.cs`. No app can lock the
/// pasteboard on a Mac, so instead of the blocking process this shows what is on it (its types, and the markers of
/// nspasteboard.org: concealed, transient, generated) and a monitor of its changes (every 600 ms, like upstream's
/// loop). Only the types are read on their own; the source app is read from the data on "Check Now" only, because
/// macOS may ask the user when an app reads the pasteboard by itself.
@MainActor
final class ClipboardSectionModel: ObservableObject {
    struct Item: Identifiable, Equatable {
        var id: String { identifier }
        var identifier: String
        var name: String
    }

    @Published private(set) var items: [Item] = []
    @Published private(set) var markers: [String] = []
    @Published private(set) var changeCount = 0
    @Published private(set) var source: String?
    @Published private(set) var monitoring = false
    @Published private(set) var monitorLog: [String] = []
    private var timer: Timer?
    private let live: Bool

    static let markerNames = ["org.nspasteboard.ConcealedType": String(localized: "Concealed (a password manager asks apps not to keep it)"),
                              "org.nspasteboard.TransientType": String(localized: "Transient (meant to be gone soon)"),
                              "org.nspasteboard.AutoGeneratedType": String(localized: "Generated by an app, not copied by the user")]

    init() {
        live = true
        refresh()
    }

    /// Fixed values (snapshots).
    init(sample types: [String], changeCount: Int, source: String?, monitorLog: [String]) {
        live = false
        apply(types: types, changeCount: changeCount)
        self.source = source
        self.monitorLog = monitorLog
        monitoring = !monitorLog.isEmpty
    }

    func refresh() {
        guard live else { return }
        let pasteboard = NSPasteboard.general
        apply(types: (pasteboard.types ?? []).map(\.rawValue), changeCount: pasteboard.changeCount)
    }

    private func apply(types: [String], changeCount: Int) {
        self.changeCount = changeCount
        markers = types.compactMap { Self.markerNames[$0] }
        items = types.filter { Self.markerNames[$0] == nil && $0 != "org.nspasteboard.source" }.map { identifier in
            Item(identifier: identifier, name: UTType(identifier)?.localizedDescription ?? "")
        }
    }

    /// Reads the types again and the app that put them there, when it says so (upstream "Test Clipboard Now").
    func checkNow() -> String {
        refresh()
        let pasteboard = NSPasteboard.general
        let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
        if pasteboard.types?.contains(sourceType) == true, let bundleID = pasteboard.string(forType: sourceType), !bundleID.isEmpty {
            let name = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
                .map { FileManager.default.displayName(atPath: $0.path) }
            source = name.map { "\($0) (\(bundleID))" } ?? bundleID
        } else {
            source = String(localized: "The app that copied it doesn't say.")
        }
        if items.isEmpty { return String(localized: "The clipboard is empty.") }
        return items.count == 1 ? String(localized: "The clipboard holds 1 type.") : String(localized: "The clipboard holds \(items.count) types.")
    }

    func toggleMonitoring() {
        monitoring ? stopMonitoring() : startMonitoring()
    }

    private func startMonitoring() {
        guard timer == nil else { return }
        monitoring = true
        monitorLog.append("\(LogViewerModel.time(Date()))  " + String(localized: "Started watching the clipboard (every 600 ms)"))
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stopMonitoring() {
        guard timer != nil else { return }
        timer?.invalidate()
        timer = nil
        monitoring = false
        monitorLog.append("\(LogViewerModel.time(Date()))  " + String(localized: "Stopped watching", comment: "Stopped watching the clipboard"))
    }

    func clearLog() {
        monitorLog.removeAll()
    }

    private func tick() {
        let count = NSPasteboard.general.changeCount
        guard count != changeCount else { return }
        refresh()
        let names = items.prefix(4).map(\.identifier).joined(separator: ", ")
        let types: String
        if items.isEmpty {
            types = String(localized: "empty", comment: "The clipboard holds nothing")
        } else if items.count > 4 {
            types = String(localized: "\(names) and \(items.count - 4) more", comment: "The first types on the clipboard, and how many more")
        } else {
            types = names
        }
        monitorLog.append("\(LogViewerModel.time(Date()))  " + String(localized: "Changed (#\(count)): \(types)"))
        if monitorLog.count > 200 { monitorLog.removeFirst(monitorLog.count - 200) }
    }
}

struct ClipboardSectionView: View {
    @ObservedObject var model: ClipboardSectionModel
    var status: (String) -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 14) {
            SectionCard(title: String(localized: "On the clipboard now")) {
                if model.items.isEmpty {
                    Text("The clipboard is empty.").foregroundStyle(.secondary)
                }
                ForEach(model.items) { item in
                    HStack(spacing: 10) {
                        Text(item.identifier).font(.body.monospaced()).textSelection(.enabled)
                        Text(item.name).foregroundStyle(.secondary)
                        Spacer()
                    }
                }
                ForEach(model.markers, id: \.self) { marker in
                    Label(marker, systemImage: "tag").foregroundStyle(.secondary)
                }
                InfoRow(label: String(localized: "Change count"), value: "\(model.changeCount)")
                if let source = model.source { InfoRow(label: String(localized: "Copied by"), value: source) }
                HStack {
                    Text("On a Mac no app can lock the clipboard, so no other app can keep \(AppInfo.name) from it.")
                        .font(.caption).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
                    Spacer()
                    Button("Check Now") { status(model.checkNow()) }
                }
            }
            SectionCard(title: String(localized: "Watch the clipboard")) {
                Text("Notes every change while it runs, every 600 ms: handy when pasting a screenshot doesn't work.")
                    .font(.caption).foregroundStyle(.secondary)
                ReportText(text: model.monitorLog.isEmpty ? String(localized: "(nothing yet)") : model.monitorLog.joined(separator: "\n"), height: 120)
                HStack {
                    Spacer()
                    Button("Clear") { model.clearLog() }
                    Button(model.monitoring ? "Stop Watching" : "Start Watching") {
                        model.toggleMonitoring()
                        status(model.monitoring ? String(localized: "Watching the clipboard.") : String(localized: "Stopped watching the clipboard."))
                    }
                }
            }
        }
    }
}
